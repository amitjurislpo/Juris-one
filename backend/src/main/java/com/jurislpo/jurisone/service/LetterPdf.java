package com.jurislpo.jurisone.service;

import java.io.IOException;

/** An issued HR letter as an A4 PDF: letterhead, reference and date, subject, the rendered text. Standard fonts only. */
public final class LetterPdf {
    private LetterPdf() {}

    public static byte[] render(String business, String address, String reference, String date, String subject, String body, String sha256) {
        try (SimplePdf simplePdf = new SimplePdf(subject, business, "Ref " + reference + " · SHA-256 " + sha256)) {
            simplePdf.line(business, 15, true, SimplePdf.INK);
            if (address != null && !address.isBlank()) {
                for (String line : simplePdf.wrap(address.replace('\n', ' '), SimplePdf.W - 2 * SimplePdf.M, 8.5f)) simplePdf.line(line, 8.5f, false, SimplePdf.MUTED);
            }
            simplePdf.gap(2);
            simplePdf.rule(SimplePdf.ACCENT, 2f);
            simplePdf.gap(6);
            simplePdf.text("Ref: " + reference, SimplePdf.M, 9.5f, true, SimplePdf.INK, false);
            simplePdf.text(date, SimplePdf.W - SimplePdf.M, 9.5f, false, SimplePdf.INK, true);
            simplePdf.gap(9);
            simplePdf.line("Subject: " + subject, 11, true, SimplePdf.INK);
            simplePdf.gap(4);
            simplePdf.paragraphs(body, 10.5f, SimplePdf.INK);
            simplePdf.gap(6);
            simplePdf.paragraphs("This letter was generated by JurisOne. Its reference number and text fingerprint are recorded in the company's HR records.", 7.5f, SimplePdf.MUTED);
            return simplePdf.finish();
        } catch (IOException e) {
            throw new IllegalStateException("letter PDF", e);
        }
    }
}
